namespace HvBackup;

/// <summary>
/// Ворота обновлений прогресса.
/// <para>
/// Фазы уборки (удаление контрольной точки, возврат исходного типа точки) отправляются
/// движком уже после того, как копирование фактически закончилось. Такое «позднее»
/// сообщение может попасть в очередь UI уже после сброса интерфейса и тогда надпись
/// фазы и анимация полосы остались бы висеть навсегда. Ворота отбрасывают такие
/// сообщения: обновление принимается, только если оно относится к текущему запуску.
/// </para>
/// <para>Все вызовы выполняются в потоке UI.</para>
/// </summary>
public sealed class ProgressGate
{
    private int _counter;
    private int _active = -1;

    /// <summary>Начинает новый запуск и возвращает его идентификатор.</summary>
    public int Begin()
    {
        _active = ++_counter;
        return _active;
    }

    /// <summary>Завершает текущий запуск — последующие обновления отбрасываются.</summary>
    public void End() => _active = -1;

    /// <summary>Актуально ли обновление указанного запуска.</summary>
    public bool IsCurrent(int runId) => runId == _active;

    /// <summary>Идентификатор текущего запуска; -1 — копирование не выполняется.</summary>
    public int ActiveId => _active;
}
